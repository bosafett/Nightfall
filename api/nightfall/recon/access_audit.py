"""Profile B playbook 8: Access-Control Assessment (design §4.8).

Inputs: two designated test identities, the first with the higher role and the second
with the lower, and up to 50 paths on the verified host that the operator says belong to
the higher role (typed in at launch, never generated by AI).

For each path it GETs the page three times: as the higher identity, as the lower identity,
and with no session. Where the higher identity gets the page and the lower identity (or no
session) gets a page too, that's reported, with whether the content matched exactly.

What it never does: change anything (GET only, apart from one sign-in POST per identity to
its registered login path), follow redirects, fetch any other host, guess paths, or store
page content. The evidence keeps status codes, redirect targets, whether a login page came
back, sizes and a short content hash; never bodies, cookie values or credentials.
Limits and stop conditions are playbook 7's: at most 200 requests, 1 per second, 30 minutes;
stops on a 429, three server errors in a row, or any sign of a locked account.
"""

from __future__ import annotations

import hashlib
import json
import re
import time
from collections.abc import Callable
from typing import Any

from nightfall.core.db.models import Confidence, RiskClass
from nightfall.recon.auth_audit import StopRun, _Session, login_form, page, sign_in
from nightfall.recon.collectors import CollectorResult, Network, RunContext
from nightfall.recon.safe_http import Exchange, Refused, SafeHttp

MAX_PATHS = 50
PATH = re.compile(r"/(?!/)[^\s#]{0,499}")


def valid_paths(raw: object) -> list[str]:
    """Paths the operator gave, re-checked here: absolute paths on the target, no scheme or
    host, no fragments or whitespace, at most 50, no duplicates. Raises ValueError."""
    if not isinstance(raw, list) or not 1 <= len(raw) <= MAX_PATHS:
        raise ValueError(f"Give 1 to {MAX_PATHS} paths.")
    out: list[str] = []
    for p in raw:
        if not isinstance(p, str) or not PATH.fullmatch(p) or "\\" in p:
            raise ValueError(f"{str(p)[:80]!r} isn't a path on the target (like /admin/users).")
        if p not in out:
            out.append(p)
    return out


def _view(ex: Exchange | None) -> dict[str, Any]:
    if ex is None:
        return {"error": True}
    return {
        "status": ex.status,
        "location": ex.location,
        "login_page": login_form(page(ex.body)) is not None,
        "length": len(ex.body),
        "sha256_16": hashlib.sha256(ex.body).hexdigest()[:16],
    }


def _gets_page(v: dict[str, Any]) -> bool:
    return v.get("status") == 200 and not v.get("login_page")


class AccessAudit:
    key = "access-audit"
    label = "Access-control assessment (Profile B)"
    risk_class = RiskClass.MODERATE
    method = (
        "GET each registered path as a higher-role and a lower-role test identity and with "
        "no session; compare status codes and content hashes"
    )

    def __init__(
        self,
        make_client: Callable[[list[Network]], SafeHttp] | None = None,
        sleep: Callable[[float], None] = time.sleep,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.make_client = make_client or (lambda nets: SafeHttp(excluded_networks=nets))
        self.sleep, self.clock = sleep, clock

    def run(self, target: str, ctx: RunContext) -> CollectorResult:
        ids = ctx.identities or []
        if len(ids) != 2:
            raise Refused("This playbook needs exactly two test identities (higher, lower).")
        origins = {i["origin"] for i in ids}
        m = re.fullmatch(r"https://([^:/]+)(?::(\d+))?", ids[0]["origin"])
        if len(origins) != 1 or not m or m.group(1) != target:
            raise Refused("Both test identities must belong to this target's origin.")
        try:
            paths = valid_paths(ctx.params.get("paths"))
        except ValueError as exc:
            raise Refused(str(exc)) from exc
        port = int(m.group(2)) if m.group(2) else None
        hi, lo = ids
        s = _Session(
            self.make_client(list(ctx.excluded_networks)), target, port, hi["label"],
            self.sleep, self.clock,
        )  # fmt: skip
        result: dict[str, Any] = {
            "higher": f"<test-identity:{hi['label']}>",
            "lower": f"<test-identity:{lo['label']}>",
            "paths": [],
            "stopped": None,
        }
        try:
            high = sign_in(s, hi)
            low = sign_in(s, lo)
            for path in paths:
                h = _view(s.send("GET", "https", path, jar=high.jar, headers=high.headers,
                                 note="as the higher identity"))  # fmt: skip
                lv = _view(s.send("GET", "https", path, jar=low.jar, headers=low.headers,
                                  note="as the lower identity"))  # fmt: skip
                a = _view(s.send("GET", "https", path, note="with no session"))
                base = _gets_page(h)
                row = {"path": path, "higher": h, "lower": lv, "anonymous": a, "baseline": base}
                if base:
                    row["lower_access"] = _gets_page(lv)
                    row["lower_same"] = row["lower_access"] and lv["sha256_16"] == h["sha256_16"]
                    row["anonymous_access"] = _gets_page(a)
                    row["anonymous_same"] = (
                        row["anonymous_access"] and a["sha256_16"] == h["sha256_16"]
                    )
                result["paths"].append(row)
        except StopRun as exc:
            result["stopped"] = str(exc)
        result["requests"] = len(s.log)
        raw = json.dumps({"target": target, "access": result, "requests": s.log}, indent=2)
        for ident in ids:
            for secret in (ident.get("password"), ident.get("username")):
                if secret and secret in raw:  # defence in depth: never store a credential
                    raw = raw.replace(secret, f"<test-identity:{ident['label']}>")
        return CollectorResult(
            raw=raw.encode(),
            content_type="application/json",
            tool_name=self.key,
            tool_version="janus-access-audit/1",
            source=self.key,
            confidence=Confidence.HIGH,
            posture={"access": result},
        )
